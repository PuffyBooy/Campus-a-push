class Handler(BaseHTTPRequestHandler):
    state: CampusState

    def log_message(self, format: str, *args: Any) -> None:  # silence
        pass

    # ------------------------------------------------------------------ helpers
    def _session(self) -> str | None:
        cookie = SimpleCookie(self.headers.get("Cookie", ""))
        sid = cookie["sid"].value if "sid" in cookie else None
        return sid if sid in self.state.sessions else None

    def _send(self, body: str, status: int = 200, headers: dict[str, str] | None = None) -> None:
        data = body.encode("utf-8")
        self.send_response(status)
        self.send_header("Content-Type", "text/html; charset=utf-8")
        self.send_header("Content-Length", str(len(data)))
        for k, v in (headers or {}).items():
            self.send_header(k, v)
        self.end_headers()
        self.wfile.write(data)

    def _redirect(self, location: str, headers: dict[str, str] | None = None) -> None:
        self.send_response(303)
        self.send_header("Location", location)
        self.send_header("Content-Length", "0")
        for k, v in (headers or {}).items():
            self.send_header(k, v)
        self.end_headers()

    def _page(self, title: str, content: str) -> str:
        if self._session():
            header = (
                '<button id="user-menu-button" type="button">Benutzermenü</button>'
                '<a href="/login?logintype=logout">Logout</a>'
            )
        else:
            header = '<a id="loginBtn" href="/login">Anmelden</a>'
        return (
            f"<!DOCTYPE html><html lang='de'><head><meta charset='utf-8'><title>{esc(title)} | campus a college"
            f"</title><style>.hidden{{display:none}}</style></head><body><header id='header'>{header}</header>"
            f"<div id='contentSection'>{content}</div></body></html>"
        )

    def _body(self) -> bytes:
        return self.rfile.read(int(self.headers.get("Content-Length", "0") or 0))

    # ------------------------------------------------------------------ routing
    def do_GET(self) -> None:
        url = urlparse(self.path)
        if url.path == "/login":
            if parse_qs(url.query).get("logintype") == ["logout"]:
                self.state.sessions.discard(self._session() or "")
            return self._send(self._page("Login", self._login_form()))
        if url.path == "/artikel/create":
            if not self._session():
                return self._redirect("/login")
            return self._send(self._page("Publizieren", self._article_form()))
        if url.path == "/profil":
            if not self._session():
                return self._redirect("/login")
            items = "".join(
                f"<li>{esc(a['fields'].get('title'))} ({esc(a['fields'].get('submitAction'))})</li>"
                for a in self.state.articles
            )
            return self._send(self._page("Profil", f'<div id="newsSection"><ul>{items}</ul></div>'))
        self._send(self._page("Nicht gefunden", "<h1>Seite nicht gefunden</h1>"), 404)

    def do_POST(self) -> None:
        url = urlparse(self.path)
        if url.path == "/login":
            form = parse_qs(self._body().decode("utf-8"))
            self.state.login_attempts += 1
            if form.get("user") == [self.state.username] and form.get("pass") == [self.state.password]:
                sid = secrets.token_hex(8)
                self.state.sessions.add(sid)
                return self._redirect("/login", {"Set-Cookie": f"sid={sid}; Path=/; HttpOnly"})
            error = '<div class="alert">Anmeldung fehlgeschlagen. Bitte prüfe E-Mail und Passwort.</div>'
            return self._send(self._page("Login", error + self._login_form()))
        if url.path == "/artikel/create" and self._session():
            fields, files = self._multipart(self._body())
            with self.state.lock:
                self.state.articles.append({"fields": fields, "files": files})
            return self._redirect("/profil")
        self._send(self._page("Fehler", "<h1>Fehler</h1>"), 400)

    def _multipart(self, body: bytes) -> tuple[dict[str, Any], dict[str, dict[str, Any]]]:
        message = email.message_from_bytes(
            f"Content-Type: {self.headers['Content-Type']}\r\n\r\n".encode() + body, policy=email.policy.default
        )
        fields: dict[str, Any] = {}
        files: dict[str, dict[str, Any]] = {}
        for part in message.iter_parts():
            name = part.get_param("name", header="content-disposition")
            short = name.replace(f"{PREFIX}[newNews]", "").replace(PREFIX, "").strip("[]").replace("][", ".")
            filename = part.get_filename()
            if filename is not None:
                payload = part.get_payload(decode=True) or b""
                if payload:
                    files[short] = {"name": filename, "size": len(payload)}
                continue
            value = (part.get_payload(decode=True) or b"").decode("utf-8")
            if name.endswith("[]"):
                fields.setdefault(short, []).append(value)
            else:
                fields[short] = value
        return fields, files

    # ------------------------------------------------------------------ markup
    def _login_form(self) -> str:
        captcha = '<div class="g-recaptcha"></div>' if self.state.captcha else ""
        return (
            '<div class="tx-sgaccount"><span>Anmeldung</span><form method="post" action="/login">'
            '<input type="hidden" name="logintype" value="login">'
            '<label for="user">E-Mail</label><input id="user" type="email" name="user">'
            '<label for="pass">Passwort</label><input id="pass" type="password" name="pass">'
            f'{captcha}<button type="submit" class="btnPrimary">Anmeldung</button></form></div>'
        )

    def _article_form(self) -> str:
        n = f"{PREFIX}[newNews]"
        options = "".join(f'<option value="{esc(k)}">{esc(v)}</option>' for k, v in self.state.tags.items())
        radios = "".join(
            f'<input id="news-category-radio-group-{v}" type="radio" name="{n}[categories]" value="{v}">'
            f'<label for="news-category-radio-group-{v}">{label}</label>'
            for v, label in ((1, "Fakten"), (2, "Meinung"), (3, "Kurzgeschichte"), (4, "Gedicht"))
        )
        resorts = "".join(
            f'<option value="{v}">{label}</option>'
            for v, label in ((6, "Kultur"), (1, "Panorama"), (2, "Politik"), (5, "Wissenschaft"))
        )
        regions = "".join(
            f'<option value="{v}">{label}</option>'
            for v, label in ((1, "International"), (2, "Österreich"), (3, "Wien"))
        )
        nav = '<button type="button" class="btnPrimary" data-next>Weiter</button>'
        draft = '<button type="submit" class="btnGray" data-action="draft">Als Entwurf speichern</button>'
        return f"""
<input type="hidden" id="role" value="EDITOR_IN_CHIEF">
<input type="hidden" id="currentSiteIdentifier" value="{esc(self.state.site_id)}">
<form id="article-form" method="post" enctype="multipart/form-data"
      action="/artikel/create?{PREFIX}%5Baction%5D=create">
<input id="submit-action" type="hidden" name="submitAction" value="">
<div id="errors"></div>
<fieldset data-step="1"><div id="news-category-radio-group">{radios}</div>{nav}</fieldset>
<fieldset data-step="2">
  <input id="isModifiedByAi" type="hidden" name="{n}[isModifiedByAi]" value="0">
  <input id="title" type="text" maxlength="130" name="{n}[title]">
  <textarea id="teaser" maxlength="500" name="{n}[teaser]"></textarea>
  <div id="story-editor"><div class="ql-editor" contenteditable="true"></div></div>
  <input id="bodytext" type="hidden" name="{n}[bodytext]" value="">
  {draft}{nav}
</fieldset>
<fieldset data-step="3">
  <input type="hidden" id="hasFalMediaFlagInput" value="0">
  <input data-crop="fileInput" class="hidden" id="falMedia" type="file" name="{PREFIX}[falMedia]">
  <input id="file_input" type="file" data-crop="fileBrowse" data-target="#falMedia">
  <div id="image-fields" style="display:none">
    <input id="falMediaConsentFirst" type="checkbox" name="{n}[falMediaConsentFirst]" value="Rechte bestätigt">
    <input id="falMediaConsentSecond" type="checkbox" name="{n}[falMediaConsentSecond]" value="Personen bestätigt">
    <input id="falMediaTitle" type="text" name="{PREFIX}[falMedia][title]">
    <input id="falMediaDescription" type="text" name="{PREFIX}[falMedia][description]">
    <input id="falMediaCopyright" type="text" name="{PREFIX}[falMedia][copyright]">
  </div>
  {draft}{nav}
</fieldset>
<fieldset data-step="4">
  <input id="datetime" type="date" name="{n}[datetime]" value="2026-10-21">
  <select id="resort" name="{n}[resorts]"><option value="">Bitte auswählen</option>{resorts}</select>
  <select id="region" name="{n}[regions]"><option value="">Bitte auswählen</option>{regions}</select>
  <div class="relative">
    <select id="tags-select" multiple name="{PREFIX}[tags][]" style="display:none">{options}</select>
    <div class="formInput cursor-text">Bitte auswählen</div>
    <div id="tags-dropdown" style="display:none">
      <input id="tags-select-search" type="text"><ul id="tags-select-listbox" role="listbox"></ul>
    </div>
  </div>
  <div class="hidden">
    <input id="alternative_title" maxlength="60" type="text" name="{n}[alternativeTitle]">
    <textarea id="metadata_description" maxlength="155" name="{n}[description]"></textarea>
  </div>
  {draft}
  <button type="submit" class="btnPrimary" data-action="published">Veröffentlichen</button>
</fieldset>
</form>
<script>{FORM_JS}</script>"""


class MockCampus:
    def __init__(self, state: CampusState | None = None):
        self.state = state or CampusState()
        handler = type("BoundCampusHandler", (Handler,), {"state": self.state})
        self.httpd = ThreadingHTTPServer(("127.0.0.1", 0), handler)
        self.thread = threading.Thread(target=self.httpd.serve_forever, daemon=True)

    @property
    def base_url(self) -> str:
        return f"http://127.0.0.1:{self.httpd.server_address[1]}"

    def __enter__(self) -> MockCampus:
        self.thread.start()
        return self

    def __exit__(self, *exc) -> None:
        self.httpd.shutdown()
        self.httpd.server_close()


