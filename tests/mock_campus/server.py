"""A small fake of the campus a author pages for browser tests.

It imitates the markup the bot relies on (taken from the saved /login and /artikel/create
pages): the sg_account login form (#user/#pass), the header user menu when logged in, the
four-step article form with the same element ids, a Quill-like story editor (``Quill.find``),
the image input that "crops" and sets #hasFalMediaFlagInput, the tag widget
(#tags-select-search / #tags-select-listbox) and the native multipart form submit. It is NOT
the real site - passing tests prove the automation logic, not compatibility with it.
"""

from __future__ import annotations

import email
